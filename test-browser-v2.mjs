import { chromium, devices } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const base='http://127.0.0.1:4173/';
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({...devices['Pixel 7'],serviceWorkers:'block'});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('dialog',async d=>d.accept());
await page.goto(base,{waitUntil:'networkidle'});
await page.getByRole('button',{name:'Treino',exact:true}).first().click();
await page.locator('input[name="muscleGroup"][value="Peito"]').check();
await page.locator('#exerciseSearch').fill('Supino');
const options=await page.locator('#exercise option').allTextContents();
assert.ok(options.some(x=>x.toLowerCase().includes('supino')),'Search filter failed');
await page.locator('#exerciseEquipment').selectOption({index:0});
assert.ok(await page.locator('#exerciseIllustration svg').count(),'Exercise SVG missing');
assert.ok(await page.locator('#exerciseIllustration ol li').count()>=2,'Instructions missing');
await page.locator('#weight').fill('20');
await page.locator('#reps').fill('10');
await page.locator('#sets').fill('3');
await page.getByRole('button',{name:'Adicionar exercício'}).click();
assert.equal(await page.locator('#exerciseSearch').inputValue(),'Supino','Search lost after save');
assert.equal(await page.locator('#weight').inputValue(),'20','Weight lost after save');
await page.screenshot({path:'treino-v2-mobile.png',fullPage:true});
await page.getByRole('button',{name:'Alimentação',exact:true}).first().click();
await page.locator('#meal').selectOption('3');
await page.locator('#grams').fill('120');
await page.getByRole('button',{name:'Salvar refeição'}).click();
assert.equal(await page.locator('#meal').inputValue(),'3','Meal lost after save');
assert.ok(await page.getByText('120 g').count(),'Meal not in history');
await page.screenshot({path:'alimentacao-v2-mobile.png',fullPage:true});
assert.deepEqual(errors,[],'Browser errors: '+errors.join('; '));
await browser.close();
console.log('PASS: mobile viewport, filters, illustrations, training persistence and meals');
